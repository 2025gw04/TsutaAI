/**
 * AIレスポンスからフェーズ情報を抽出
 */
function extractPhasesFromResponse(response) {
    // ```phases ... ``` ブロックを探す
    const phasesMatch = response.match(/```phases\s*([\s\S]*?)```/);
    if (phasesMatch) {
        try {
            const jsonStr = phasesMatch[1].trim();
            const phases = JSON.parse(jsonStr);
            if (Array.isArray(phases) && phases.length > 0) {
                return phases;
            }
        } catch (e) {
            console.error('フェーズJSONのパースエラー:', e);
        }
    }

    // 通常のJSONブロックも試す
    const jsonMatch = response.match(/```(?:json)?\s*(\[[\s\S]*?\])\s*```/);
    if (jsonMatch) {
        try {
            const phases = JSON.parse(jsonMatch[1]);
            // フェーズデータかどうかを確認
            if (Array.isArray(phases) && phases.length > 0 && phases[0].phaseName) {
                return phases;
            }
        } catch (e) {
            // パース失敗は無視
        }
    }

    return null;
}

